/**
 * 按年代排序的时间线（数组已按时间排列，此函数供视图复用）
 * @returns {AstronomerEntry[]}
 */
export function getTimelineEntries() {
  return ASTRONOMER_TIMELINE
}

/**
 * @param {string} id
 * @returns {AstronomerEntry | undefined}
 */
export function getAstronomerById(id) {
  return ASTRONOMER_TIMELINE.find((e) => e.id === id)
}

/**
 * @returns {{ count: number, span: string }}
 */
export function timelineStats() {
  const first = ASTRONOMER_TIMELINE[0]
  const last = ASTRONOMER_TIMELINE[ASTRONOMER_TIMELINE.length - 1]
  const fmtYear = (y) => y < 0 ? `前${Math.abs(y)}` : String(y)
  return {
    count: ASTRONOMER_TIMELINE.length,
    span: `${fmtYear(first.dateRange.start)} — ${fmtYear(last.dateRange.end)}`
  }
}
