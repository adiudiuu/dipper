/**
 * 获取今日文化小知识
 * @param {{ termName: string, festivals?: Array<{ name: string }> }} ctx
 * @returns {{ kind: 'festival'|'jieqi', title: string, lines: string[] } | null}
 */
export function getTodayCultureTip(ctx) {
  const festivals = ctx.festivals || []
  if (festivals.length) {
    const f = festivals[0]
    const tip = FESTIVAL_TIPS[f.name]
    if (tip) {
      const lines = [tip.custom]
      if (tip.note) lines.push(tip.note)
      return { kind: 'festival', title: f.name, lines }
    }
  }

  const jq = JIEQI_TIPS[ctx.termName]
  if (jq) {
    const lines = [jq.wuhou]
    if (jq.custom) lines.push(jq.custom)
    return { kind: 'jieqi', title: ctx.termName, lines }
  }

  return null
}
